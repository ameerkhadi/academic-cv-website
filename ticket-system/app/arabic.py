# -*- coding: utf-8 -*-
"""صياغةُ الأعداد بالعربيّة: الأرقامُ الهنديّة، وتمييزُ العدد على وجهه.

القاعدة: الواحدُ مفرد، والاثنان مثنّى، ومن ثلاثةٍ إلى عشرةٍ جمع،
وما جاوز العشرةَ مفردٌ منصوب.
"""
AR = str.maketrans("0123456789", "٠١٢٣٤٥٦٧٨٩")

# المثنّى بصيغة الجرّ لا الرفع، لأنّ العددَ هنا يقع بعد «منذ» و«بعد» و«حتّى».
UNITS = {
    "يوم":   ("يوم",   "يومين",   "أيّام",  "يومًا"),
    "ساعة":  ("ساعة",  "ساعتين",  "ساعات",  "ساعةً"),
    "دقيقة": ("دقيقة", "دقيقتين", "دقائق",  "دقيقةً"),
    "تذكرة": ("تذكرة", "تذكرتين", "تذاكر",  "تذكرةً"),
}


def num(v) -> str:
    return str(v).translate(AR)


def count(n: int, unit: str) -> str:
    """يُرجع العددَ ومعدودَه مضبوطًا، مثل «يومان» و«٣ أيّام» و«١١ يومًا»."""
    one, two, few, many = UNITS.get(unit, (unit, unit, unit, unit))
    n = int(n)
    if n == 1:
        return one
    if n == 2:
        return two
    r = n % 100
    if 3 <= r <= 10:                      # ٣ أيّام … ١٠ أيّام
        return "%s %s" % (num(n), few)
    if r == 0 and n >= 100:               # ١٠٠ يوم · ٢٠٠ يوم
        return "%s %s" % (num(n), one)
    return "%s %s" % (num(n), many)       # ١١ يومًا · ١٠١ يومًا
