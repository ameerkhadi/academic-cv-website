# -*- coding: utf-8 -*-
"""التصنيفُ التلقائيّ: من نصِّ الشكوى إلى فئةٍ ودرجةِ إلحاحٍ وجهةِ إحالة.

القواعدُ هي قواعدُ الدائرة المكتوبة، مُنفَّذةً كما هي:
  الفئات   — خمسٌ لا سادسَ لها.
  الإلحاح  — عاليةٌ عند تجاوز المدّة القانونيّة أو الأثر الماليّ المباشر،
             متوسّطةٌ عند تأخيرٍ دون المدّة، ودنيا للاستفسار وطلب المعلومة.
  الإحالة  — جدولٌ ثابتٌ من الفئة إلى الشعبة.

والتنفيذُ محلّيٌّ بلا خدمةٍ خارجيّة، فيعمل على خادمٍ بلا إنترنت، ونتيجتُه
ثابتةٌ لا تتغيّر بين تشغيلٍ وآخر — وهذا شرطُ القبول في العمل الرسميّ.
"""
import re
from . import config
from .arabic import num as ar_num

# ── مفاتيحُ كلّ فئة، ولكلِّ مفتاحٍ وزنُه ──
CATEGORY_KEYS = {
    "تأخير": [
        (r"تأخ[يّ]ر|متأخ|لم ?يُ?نجز|ما ?خلص|ماخلص|منذ ?(أسبوع|شهر|مدة)|انتظر|لم ?يصل|ما ?وصل", 3),
        (r"مضى|مرّ[ت]? ?\d+ ?(يوم|أيام|شهر|أشهر|أسبوع)", 3),
        (r"وعدوني|راجعت ?عدّ?ة ?مرات|مراجعات ?متكررة", 2),
    ],
    "خطأ بيانات": [
        (r"خطأ ?في ?(الاسم|البيانات|الرقم|التاريخ|المعلوم)|اسمي ?(غلط|خطأ|مكتوب ?غلط)", 3),
        (r"غير ?صحيح|مغلوط|سهو|تصحيح ?(الاسم|البيانات|المعلومة)|معلومة ?خاطئة", 3),
        (r"رقم ?(المعاملة|الهوية|الوطنية) ?(غلط|خطأ|غير ?صحيح)", 3),
    ],
    "رفض غير مبرَّر": [
        (r"رفض|رُفض|رفضوا|اعتُرض|لم ?يُ?قبل|ما ?قبلوا|مرفوض", 3),
        (r"بلا ?(سبب|مبرر)|بدون ?(سبب|مبرر)|غير ?مبرر|لم ?يُ?بيّ?نوا ?السبب", 3),
        (r"استُثنيت|حرموني|منعوني", 2),
    ],
    "سوء تعامل": [
        (r"سوء ?(تعامل|معاملة)|أساء|إساءة|تطاول|صراخ|صرخ|شتم|استهزاء|احتقار", 3),
        (r"غير ?لائق|تعامل ?سيّ?ئ|أسلوب ?(سيّ?ئ|غير ?لائق)|قلّة ?احترام|عدم ?احترام", 3),
        (r"تجاهلني|تجاهل|لم ?يعرني|رفع ?صوته", 2),
    ],
}

# ── مفاتيحُ درجة الإلحاح ──
HIGH_KEYS = [
    r"تجاوز[تن]? ?المدّ?ة ?القانون|المدّ?ة ?القانون[يّ]ة|خارج ?المدّ?ة ?القانون",
    r"خصم|غرامة|راتب|مستحقات|مبلغ|دينار|مالي[ًا]?|تعويض|أجور|استقطاع",
    r"\d+ ?(شهر|أشهر|سنة|سنوات|يوم|أيام)",
    r"(شهرين|سنتين|عامين|أسبوعين)",
    r"(ثلاثة|أربعة|خمسة|ستة|سبعة|ثمانية|تسعة|عشرة) ?(أشهر|شهور|سنوات)",
]
LOW_KEYS = [
    r"استفسار|أستفسر|سؤال|أسأل|أرجو ?(العلم|الإفادة|التوضيح)|طلب ?معلوم|كيف ?(أ|ا)",
    r"ما ?هي ?(الإجراءات|الخطوات|الشروط)|أين ?(أراجع|أقدّ?م)|متى ?(يُ?فتح|الدوام)",
]
MED_KEYS = [
    r"تأخ[يّ]ر|متأخ|انتظر|لم ?ينجز|ما ?خلص",
]


def _norm(t: str) -> str:
    """تطبيعٌ خفيف: حذفُ التشكيل وتوحيدُ الألف والهاء، ليُطابَق النصُّ كما يكتبه الناس."""
    t = re.sub(r"[ً-ْـ]", "", t or "")
    t = t.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")
    t = t.replace("ة", "ه").replace("ى", "ي").replace("ؤ", "و").replace("ئ", "ي")
    return re.sub(r"\s+", " ", t).strip()


def _score(text: str, rules) -> int:
    n = _norm(text)
    total = 0
    for pat, w in rules:
        if re.search(_norm(pat), n):
            total += w
    return total


def classify(subject: str, body: str):
    """يُرجع (الفئة، الإلحاح، الشعبة، تفسيرٌ مختصرٌ لسبب القرار)."""
    text = "%s\n%s" % (subject or "", body or "")

    scores = {cat: _score(text, rules) for cat, rules in CATEGORY_KEYS.items()}
    best = max(scores, key=lambda k: scores[k])
    if scores[best] == 0:
        category, why_cat = "أخرى", "لم تُطابِق الشكوى مفاتيحَ أيٍّ من الفئات الأربع"
    else:
        category = best
        why_cat = "طابقت مفاتيحَ فئة «%s» بوزن %s" % (best, ar_num(scores[best]))

    n = _norm(text)
    if any(re.search(_norm(p), n) for p in HIGH_KEYS):
        priority, why_pri = "عالية", "ورد فيها ما يدلّ على تجاوز المدّة القانونيّة أو أثرٍ ماليّ مباشر"
    elif any(re.search(_norm(p), n) for p in LOW_KEYS):
        priority, why_pri = "دنيا", "صيغتُها صيغةُ استفسارٍ أو طلبِ معلومة"
    elif any(re.search(_norm(p), n) for p in MED_KEYS) or category != "أخرى":
        priority, why_pri = "متوسطة", "شكوى عملٍ دون ما يرفعها إلى الدرجة العليا"
    else:
        priority, why_pri = "دنيا", "لا قرينةَ على إلحاحٍ في النصّ"

    dept = config.ROUTING[category]
    why = "%s — %s. والإحالةُ إلى «%s» بحكم جدول الإحالة." % (why_cat, why_pri, dept)
    return category, priority, dept, why
